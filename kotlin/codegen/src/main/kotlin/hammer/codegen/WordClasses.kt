package hammer.codegen

import java.io.File

/**
 * What each code point is to the kits' `words`: [LETTER]s make words, [MARK]s stay on the letter before
 * them, each [IDEOGRAPH] is a word of its own (Chinese and Japanese put no spaces between words), and a
 * [JOINER] between two letters stays inside the word. Anything else ends a word.
 */
const val OTHER = 0
const val LETTER = 1
const val MARK = 2
const val IDEOGRAPH = 3
const val JOINER = 4

/** Apostrophes, the Catalan middle dot, Hebrew's geresh and gershayim, ZWNJ, ZWJ, and the soft hyphen. */
private val joiners = listOf(0x27, 0x2019, 0xB7, 0x5F3, 0x5F4, 0x200C, 0x200D, 0xAD)

/** Katakana's prolonged sound marks, which Scripts.txt files under Common. */
private val ideographExtras = listOf(0x30FC, 0xFF70)

private val ideographScripts = setOf("Han", "Hiragana", "Katakana", "Bopomofo")

/** Runs of code points of one class other than [OTHER], as `[first, last, class]`, in order. */
fun wordClassRanges(unicodeData: String, scripts: String): List<IntArray> {
	val classes = sortedMapOf<Int, Int>()
	var first = -1
	unicodeData.lineSequence().filter { it.isNotBlank() }.forEach { line ->
		val fields = line.split(';')
		val code = fields[0].toInt(16)
		val category = fields[2]
		if (fields[1].endsWith("First>")) {
			first = code
			return@forEach
		}
		val cls = when {
			category.startsWith("L") || category == "Nl" -> LETTER
			category.startsWith("M") -> MARK
			else -> return@forEach
		}
		val from = if (fields[1].endsWith("Last>")) first else code
		for (c in from..code) classes[c] = cls
	}
	scripts.lineSequence().map { it.substringBefore('#').trim() }.filter { it.isNotEmpty() }.forEach { line ->
		val (range, script) = line.split(';').map { it.trim() }
		if (script !in ideographScripts) return@forEach
		val from = range.substringBefore("..").toInt(16)
		val to = range.substringAfter("..", range).toInt(16)
		for (c in from..to) if (classes[c] == LETTER) classes[c] = IDEOGRAPH
	}
	ideographExtras.forEach { classes[it] = IDEOGRAPH }
	joiners.forEach { classes[it] = JOINER }

	val ranges = mutableListOf<IntArray>()
	for ((code, cls) in classes) {
		val last = ranges.lastOrNull()
		if (last != null && last[1] == code - 1 && last[2] == cls) last[1] = code else ranges += intArrayOf(code, code, cls)
	}
	return ranges
}

private const val HEADER = "Generated by gradle :codegen:generateWordClasses from Unicode"

private fun rows(ranges: List<IntArray>, indent: String, format: (IntArray) -> String) =
	ranges.chunked(6).joinToString("\n") { row -> indent + row.joinToString(" ", transform = format) }

fun kotlinWordClasses(ranges: List<IntArray>, version: String) = """
	|// $HEADER $version. Do not edit.
	|package hammer
	|
	|/** Runs of code points as first, last, and class, in order; a code point in none is OTHER. */
	|internal val WORD_CLASSES = intArrayOf(
	|${rows(ranges, "\t") { "0x%X, 0x%X, %d,".format(it[0], it[1], it[2]) }}
	|)
	|""".trimMargin()

fun rustWordClasses(ranges: List<IntArray>, version: String) = """
	|// $HEADER $version. Do not edit.
	|
	|/// Runs of code points as first, last, and class, in order; a code point in none is OTHER.
	|pub(crate) static WORD_CLASSES: [(u32, u32, u8); ${ranges.size}] = [
	|${rows(ranges, "    ") { "(0x%X, 0x%X, %d),".format(it[0], it[1], it[2]) }}
	|];
	|""".trimMargin()

fun cWordClasses(ranges: List<IntArray>, version: String) = """
	|// $HEADER $version. Do not edit.
	|#ifndef HAMMER_WORD_CLASSES_H
	|#define HAMMER_WORD_CLASSES_H
	|
	|#include <stdint.h>
	|
	|// Runs of code points as first, last, and class, in order; a code point in none is HAMMER_OTHER.
	|static const uint32_t hammer_word_classes[][3] = {
	|${rows(ranges, "  ") { "{0x%X, 0x%X, %d},".format(it[0], it[1], it[2]) }}
	|};
	|
	|#endif // HAMMER_WORD_CLASSES_H
	|""".trimMargin()

/** Usage: word-classes <Unicode version> <UCD directory> <Kotlin file> <Rust file> <C header> */
fun main(args: Array<String>) {
	require(args.size == 5) { "Usage: word-classes <version> <ucd dir> <kotlin file> <rust file> <c header>" }
	val (version, ucd) = args
	val ranges = wordClassRanges(File(ucd, "UnicodeData.txt").readText(), File(ucd, "Scripts.txt").readText())
	File(args[2]).writeText(kotlinWordClasses(ranges, version))
	File(args[3]).writeText(rustWordClasses(ranges, version))
	File(args[4]).writeText(cWordClasses(ranges, version))
	println("Generated ${ranges.size} word class ranges from Unicode $version")
}
